<?php

declare(strict_types=1);

namespace AppGuard\Core\Snapshot;

final class CompiledRulesSnapshot
{
    private static ?string $customBasePath = null;

    /** @var array<string, array<string, mixed>> */
    private static array $memoryCache = [];

    public static function setBasePath(?string $path): void
    {
        self::$customBasePath = $path !== null ? rtrim($path, '/\\') : null;
    }

    public static function getBasePath(): string
    {
        if (self::$customBasePath !== null) {
            return self::$customBasePath;
        }

        if (function_exists('storage_path')) {
            return storage_path('app/guard');
        }

        return sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'app_guard';
    }

    public static function getFilePath(string $appKey, ?string $baseDir = null): string
    {
        $dir = $baseDir !== null ? rtrim($baseDir, '/\\') : self::getBasePath();
        return $dir . DIRECTORY_SEPARATOR . "rules_{$appKey}.php";
    }

    /**
     * Tulis hasil sinkronisasi rules dan banned IPs dari Control Plane ke file PHP compiled lokal.
     *
     * @param array<string, mixed> $data
     */
    public static function write(string $appKey, array $data, ?string $baseDir = null): string
    {
        $targetPath = self::getFilePath($appKey, $baseDir);
        $dir = dirname($targetPath);

        if (! is_dir($dir)) {
            @mkdir($dir, 0755, true);
        }

        // 1. Transformasikan banned_ips menjadi O(1) hash map
        $rawBanned = $data['banned_ips'] ?? [];
        $bannedMap = [];
        if (is_array($rawBanned)) {
            if (array_is_list($rawBanned)) {
                foreach ($rawBanned as $ip) {
                    if (is_string($ip) && trim($ip) !== '') {
                        $bannedMap[trim($ip)] = 1;
                    }
                }
            } else {
                foreach ($rawBanned as $ip => $val) {
                    if (is_string($ip) && trim($ip) !== '') {
                        $bannedMap[trim($ip)] = 1;
                    }
                }
            }
        }

        // 2. Normalisasi honeypots
        $honeypots = [];
        if (! empty($data['honeypots']) && is_array($data['honeypots'])) {
            $honeypots = array_values(array_unique(array_filter($data['honeypots'], 'is_string')));
        }

        $compiled = [
            'app_key' => $appKey,
            'synced_at' => time(),
            'etag' => (string) ($data['etag'] ?? ''),
            'policy' => is_array($data['policy'] ?? null) ? $data['policy'] : [],
            'thresholds' => is_array($data['thresholds'] ?? null) ? $data['thresholds'] : [],
            'honeypots' => $honeypots,
            'banned_ips' => $bannedMap,
        ];

        $export = var_export($compiled, true);
        $phpCode = "<?php\n\n// Auto-generated by AppGuard Compiled Snapshot Engine. Do not edit directly.\nreturn {$export};\n";

        // 3. Atomic file write (tmp file -> rename)
        $tmpPath = $targetPath . '.tmp.' . bin2hex(random_bytes(4));
        file_put_contents($tmpPath, $phpCode, LOCK_EX);
        rename($tmpPath, $targetPath);

        // 4. Invalidate OPcache jika tersedia
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($targetPath, true);
        }

        // 5. Update cache memori in-process
        self::$memoryCache[$appKey] = $compiled;

        return $targetPath;
    }

    /**
     * Memuat snapshot compiled rules.
     *
     * @return array<string, mixed>|null
     */
    public static function load(string $appKey, ?string $baseDir = null, bool $fresh = false): ?array
    {
        if ($appKey === '') {
            return null;
        }

        if (! $fresh && isset(self::$memoryCache[$appKey])) {
            return self::$memoryCache[$appKey];
        }

        $filePath = self::getFilePath($appKey, $baseDir);
        if (! file_exists($filePath)) {
            return null;
        }

        try {
            $data = (static function (string $file): mixed {
                return @include $file;
            })($filePath);

            if (is_array($data)) {
                self::$memoryCache[$appKey] = $data;
                return $data;
            }
        } catch (\Throwable) {
            // Fail-open
        }

        return null;
    }

    /**
     * Cek apakah IP terdaftar di blacklist snapshot (Lookup O(1) hash map).
     */
    public static function isIpBanned(string $ip, string $appKey, ?string $baseDir = null): bool
    {
        if ($ip === '' || $appKey === '') {
            return false;
        }

        $snapshot = self::load($appKey, $baseDir);
        if ($snapshot === null || empty($snapshot['banned_ips'])) {
            return false;
        }

        return isset($snapshot['banned_ips'][$ip]);
    }

    /**
     * Ambil seluruh banned IPs dari snapshot sebagai list IP (misal untuk audit/status CLI).
     *
     * @return string[]
     */
    public static function getBannedIps(string $appKey, ?string $baseDir = null): array
    {
        $snapshot = self::load($appKey, $baseDir);
        if ($snapshot === null || empty($snapshot['banned_ips']) || ! is_array($snapshot['banned_ips'])) {
            return [];
        }

        return array_keys($snapshot['banned_ips']);
    }

    /**
     * Ambil jumlah IP yang ter-ban di snapshot.
     */
    public static function countBannedIps(string $appKey, ?string $baseDir = null): int
    {
        $snapshot = self::load($appKey, $baseDir);
        return $snapshot !== null && isset($snapshot['banned_ips']) && is_array($snapshot['banned_ips'])
            ? count($snapshot['banned_ips'])
            : 0;
    }

    /**
     * Hapus berkas snapshot dan bersihkan memori cache.
     */
    public static function delete(string $appKey, ?string $baseDir = null): bool
    {
        unset(self::$memoryCache[$appKey]);
        $filePath = self::getFilePath($appKey, $baseDir);
        if (file_exists($filePath)) {
            if (function_exists('opcache_invalidate')) {
                @opcache_invalidate($filePath, true);
            }
            return @unlink($filePath);
        }
        return false;
    }

    /**
     * Reset memory cache (berguna saat worker/testing).
     */
    public static function clearMemoryCache(): void
    {
        self::$memoryCache = [];
    }
}

